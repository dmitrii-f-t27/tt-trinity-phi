"""Runs INSIDE the pinned LibreLane image, with no network (sidecar 9b).

Loads the archived stage-41 config and the archived stage-41 OUTPUT state through the pinned LibreLane API,
using a subclass of the real OpenROAD.RepairDesignPostGRT step whose only differences are: the Tcl script
(observe.tcl: no repair, no resize, no placement, no write of any view) and outputs = [] (no views are saved).
The parent ResizerStep.run passes RSZ_CORNERS or STA_CORNERS, so the 9 liberty corners and the RC set-up are
generated by LibreLane itself. The archived config is used unchanged (the archive and the PDK are mounted at
their original absolute paths). Inputs are hashed before and after. Any mismatch fails (exit 1).
--pdk-root is the archived PDK_ROOT value (the pinned PDK version directory); the loaded PDK_ROOT and DESIGN_DIR
must come back unchanged, the effective SDC must be the pinned base.sdc (sha256), and the model files must lie in
the pinned PDK version.
Usage: python3 measure_step.py --config C --state-in S --pdk-root P --tcl T --out DIR
"""
import argparse
import hashlib
import json
import os
import shutil
import sys
from decimal import Decimal

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as c  # noqa: E402  (standard library only)

EXPECT = {
    "DEFAULT_CORNER": "nom_tt_025C_1v80",
    "CLOCK_PERIOD": Decimal("40"),
    "MAX_TRANSITION_CONSTRAINT": Decimal("0.75"),
    "MAX_FANOUT_CONSTRAINT": 10,
    "RSZ_CORNERS": None,
    "PNR_CORNERS": None,
    "PNR_SDC_FILE": None,
    "PDK": "sky130A",
}
# Path-valued settings that must come back from Step.load exactly as archived (no rewrite)
EXPECT_PATHS = {"PDK_ROOT": c.PDK_VERSION_ROOT, "DESIGN_DIR": c.WORK_ROOT + "/src"}
CORNERS = c.CORNERS
EXCLUDED = ["sky130_fd_sc_hd__clkdlybuf*", "sky130_fd_sc_hd__dlygate*", "sky130_fd_sc_hd__dlymetal*"]


def sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def files_of(value):
    """Flatten a config value (path, list, or wildcard dict of lists) into existing-or-not path strings."""
    if value is None:
        return []
    if isinstance(value, dict):
        return [p for v in value.values() for p in files_of(v)]
    if isinstance(value, (list, tuple)):
        return [p for v in value for p in files_of(v)]
    return [str(value)]


def main():
    ap = argparse.ArgumentParser()
    for a in ("--config", "--state-in", "--pdk-root", "--tcl", "--out"):
        ap.add_argument(a, required=True)
    args = ap.parse_args()
    prov = {"problems": [], "pdk_root_arg": args.pdk_root}
    if os.path.normpath(args.pdk_root) != c.PDK_VERSION_ROOT:
        prov["problems"].append("--pdk-root %r is not the pinned PDK version directory" % args.pdk_root)

    def done():
        prov["status"] = "PASS" if not prov["problems"] else "FAIL"
        with open(os.path.join(args.out, "measure-provenance.json"), "w", encoding="utf-8") as f:
            json.dump(prov, f, indent=2, sort_keys=True, default=str)
        for p in prov["problems"]:
            print("STAGE41_MEASURE FAIL:", p)
        print("STAGE41_MEASURE", prov["status"])
        return 0 if prov["status"] == "PASS" else 1

    os.makedirs(args.out, exist_ok=True)
    try:
        from librelane.__version__ import __version__
        from librelane.common import Toolbox
        from librelane.steps.openroad import RepairDesignPostGRT
    except ImportError as e:
        prov["problems"].append("pinned LibreLane is not importable here: %s" % e)
        return done()
    prov["librelane_version"] = __version__
    if __version__ != "3.0.14":
        prov["problems"].append("LibreLane %s, expected 3.0.14" % __version__)

    tcl = os.path.abspath(args.tcl)

    class Stage41Observe(RepairDesignPostGRT):
        outputs = []

        def get_script_path(self):
            return tcl

    inputs = {"config": args.config, "state_in": args.state_in, "tcl": tcl}
    with open(args.state_in, encoding="utf-8") as f:
        state_json = json.load(f)
    inputs["odb"] = state_json.get("odb")
    for name, path in inputs.items():
        if not path or not os.path.isfile(path):
            prov["problems"].append("input %s missing: %r" % (name, path))
    if prov["problems"]:
        return done()
    prov["hash_before"] = {k: sha(v) for k, v in inputs.items()}

    try:
        step = Stage41Observe.load(config=args.config, state_in=args.state_in, pdk_root=args.pdk_root)
    except Exception as e:  # noqa: BLE001 - any load failure is a diagnostic failure
        prov["problems"].append("Step.load failed: %s: %s" % (type(e).__name__, e))
        return done()
    cfg = step.config
    prov["config"] = {k: cfg.get(k) for k in list(EXPECT) + ["STA_CORNERS", "EXTRA_EXCLUDED_CELLS", "PNR_SDC_FILE",
                                                             "FALLBACK_SDC", "LAYERS_RC", "VIAS_R",
                                                             "SIGNAL_WIRE_RC_LAYERS", "CLOCK_WIRE_RC_LAYERS",
                                                             "GRT_ADJUSTMENT", "GRT_OVERFLOW_ITERS",
                                                             "GRT_ALLOW_CONGESTION", "DEDUPLICATE_CORNERS"]}
    for key, want in EXPECT.items():
        if cfg.get(key) != want:
            prov["problems"].append("config %s is %r, expected %r" % (key, cfg.get(key), want))
    for key, want in EXPECT_PATHS.items():
        got = str(cfg.get(key)).rstrip("/") if cfg.get(key) is not None else None
        prov["config"][key] = got
        if got != want:
            prov["problems"].append("config %s is %r after load, expected %r" % (key, got, want))
        elif not os.path.isdir(got):
            prov["problems"].append("config %s directory not mounted: %s" % (key, got))
    if list(cfg.get("STA_CORNERS") or []) != CORNERS:
        prov["problems"].append("config STA_CORNERS %r != the 9 expected corners" % cfg.get("STA_CORNERS"))
    if list(cfg.get("EXTRA_EXCLUDED_CELLS") or []) != EXCLUDED:
        prov["problems"].append("config EXTRA_EXCLUDED_CELLS %r != %r" % (cfg.get("EXTRA_EXCLUDED_CELLS"), EXCLUDED))
    sdc = cfg.get("PNR_SDC_FILE") or cfg.get("FALLBACK_SDC")
    prov["effective_sdc"] = {"path": str(sdc) if sdc else None,
                             "source": "PNR_SDC_FILE" if cfg.get("PNR_SDC_FILE") else "FALLBACK_SDC",
                             "sha256": sha(str(sdc)) if sdc and os.path.isfile(str(sdc)) else None}
    if prov["effective_sdc"]["sha256"] != c.BASE_SDC_SHA256:
        prov["problems"].append("effective SDC (_SDC_IN) %r sha256 %r != pinned base.sdc %s"
                                % (sdc, prov["effective_sdc"]["sha256"], c.BASE_SDC_SHA256))
    prov["model_files"] = {}
    for key in ("LIB", "TECH_LEFS", "CELL_LEFS"):
        for p in files_of(cfg.get(key)):
            prov["model_files"][p] = sha(p) if os.path.isfile(p) else None
            if prov["model_files"][p] is None:
                prov["problems"].append("%s file missing: %s" % (key, p))
            elif not p.startswith(c.PDK_VERSION_ROOT + "/"):
                prov["problems"].append("%s file outside the pinned PDK version: %s" % (key, p))
    if not prov["model_files"]:
        prov["problems"].append("no liberty / LEF model files in the config")
    if prov["problems"]:
        return done()

    try:
        step.start(toolbox=Toolbox(os.path.join(args.out, "toolbox_tmp")), step_dir=args.out)
    except Exception as e:  # noqa: BLE001
        prov["problems"].append("observation step failed: %s: %s" % (type(e).__name__, e))
    log = step.get_log_path() if getattr(step, "step_dir", None) else None
    if log and os.path.isfile(log):
        shutil.copy(log, os.path.join(args.out, "stage41-openroad.log"))
    else:
        prov["problems"].append("OpenROAD log missing")
    for name in ("stage41-design-before.tsv", "stage41-design-after.tsv"):
        path = os.path.join(args.out, name)
        prov.setdefault("design_records", {})[name] = sha(path) if os.path.isfile(path) else None
        if prov["design_records"][name] is None:
            prov["problems"].append("%s missing" % name)

    prov["hash_after"] = {k: sha(v) for k, v in inputs.items()}
    if prov["hash_after"] != prov["hash_before"]:
        prov["problems"].append("an input changed during the observation")
    return done()


if __name__ == "__main__":
    sys.exit(main())
